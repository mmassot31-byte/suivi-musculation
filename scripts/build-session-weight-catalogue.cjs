// JSON remains the editorial source. A static module avoids JSON import support
// differences in iOS Safari and any catalogue fetch when finishing a workout.
const fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'..'),catalogue=JSON.parse(fs.readFileSync(path.join(root,'session-weight-catalogue.json'),'utf8'));
const content='// Generated by npm run build:session-weight. Edit session-weight-catalogue.json.\nexport default '+JSON.stringify(catalogue)+';\n';
const target=path.join(root,'session-weight-catalogue.js');
if(process.argv.includes('--check')){
 if(!fs.existsSync(target)||fs.readFileSync(target,'utf8')!==content){console.error('Catalogue module is out of date. Run npm run build:session-weight.');process.exitCode=1;}
}else fs.writeFileSync(target,content);
