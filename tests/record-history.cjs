const assert=require('node:assert/strict');
(async()=>{
 const {distinctRecordHistory,performanceDashboardHtml}=await import('../performance-overview.js');
 const identity={version:1,unit:'kg',convention:'Total',lateralMode:'total',source:'confirmed'};
 const ex=(w,r,extra=[])=>({id:'test-record',name:'Exercice test',loadIdentity:identity,sets:[{id:'set',w,r,type:'work',loadIdentity:identity},...extra]});
 const session=(id,day,e)=>({id,date:day+'T12:00:00Z',endedAt:day+'T13:00:00Z',exercises:[e]});
 const today='2026-11-08',old=session('old','2026-09-01',ex(60,8)),latest=session('latest','2026-11-07',ex(60,10,[{id:'repeat',w:60,r:10,type:'work',loadIdentity:identity}]));
 let state={sessions:[old,latest]},before=structuredClone(state),rows=distinctRecordHistory(state,{today});
 assert.equal(rows.filter(x=>x.record.kind==='reps').length,1,'Identical sets form one repetition record');
 assert.deepEqual(rows.find(x=>x.record.kind==='reps').gain,{value:2,unit:'rép.'},'Baseline outside selected period still used');
 assert(rows.some(x=>x.record.kind==='tonnage'),'Session tonnage remains a distinct record');
 assert(rows.filter(x=>x.record.kind==='tonnage').every(x=>x.record.value===1200));
 assert.equal(distinctRecordHistory(state,{today,kind:'weight'}).length,0);
 assert.deepEqual(state,before);
 assert.equal(distinctRecordHistory({sessions:[latest]},{today}).length,0,'First observation is not an invented record');
 rows=distinctRecordHistory({sessions:[old,session('new','2026-11-07',ex(65,6))]},{today});
 assert.equal(rows.find(x=>x.record.kind==='weight').gain,null,'Different reps cannot invent a comparable weight gain');
 rows=distinctRecordHistory({sessions:[old,session('new','2026-11-07',ex(65,8))]},{today});
 assert.deepEqual(rows.find(x=>x.record.kind==='weight').gain,{value:5,unit:'kg'});
 const mismatch=structuredClone(old);mismatch.exercises[0].sets[0].loadIdentity={...identity,unit:'lb'};
 assert.equal(distinctRecordHistory({sessions:[mismatch,latest]},{today}).length,0,'Different load units are not comparable');
 const doubled=distinctRecordHistory({sessions:[old,latest,structuredClone(latest)]},{today});
 assert.equal(doubled.filter(x=>x.record.kind==='reps').length,1);
 assert.equal(distinctRecordHistory(state,{today:'2026-12-30',days:7}).length,0);
 assert(distinctRecordHistory(state,{today:'2026-12-30',all:true}).length>0);
 const html=performanceDashboardHtml(state,{today,tab:'records'});
 assert.match(html,/1 200 kg·rép\./);assert.doesNotMatch(html,/record-mini|progressbar/);
 console.log('PASS distinct record history: duplicate sets/sessions, distinct types, true tonnage, comparable gains, older baseline, no baseline/unit mismatch, filters and immutable source');
})().catch(e=>{console.error(e);process.exitCode=1});
